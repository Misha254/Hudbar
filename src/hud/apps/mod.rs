//! Окно приложений: скан desktop-файлов, поиск, закрепление и запуск.
//!
//! Модуль собран из пяти независимых частей, и ни одна из них не знает про
//! Wayland:
//!
//! - `scan` — desktop-файлы: каталоги, локализованные имена, `Exec`, иконка;
//! - `search` — что считается совпадением и в каком порядке выдача;
//! - `model` — строки, запрос, выбор, закрепление;
//! - `pins` — файл закреплённых и перенос из прежнего окна rofi;
//! - `launch` — разбор `Exec` и запуск;
//! - `icons` — поиск файла иконки, растеризация SVG/PNG, кэш и очередь;
//! - `view` — карточка окна.
//!
//! Замена прежнего `rofi -show hudapps` целиком: тот же список, те же
//! закреплённые, но окно рисуется тем же кодом, что панель и меню, и работает
//! без X11.

pub mod icons;
pub mod keys;
pub mod launch;
pub mod model;
pub mod pins;
pub mod scan;
pub mod search;
pub mod snapshot;
pub mod view;
