//! Мост Telegram ↔ opencode: телефон как пульт сессии.
//!
//! Мост работает без Wayland и без окна. Два направления:
//!
//! - **команды**: апдейт из Telegram разбирается в действие и уходит в
//!   HTTP-API opencode (`hud/telegram/opencode`): промпт в сессию, ответ на
//!   запрос прав, прерывание, список сессий;
//! - **события**: поток `GET /event` той же машины читает ответы агента и
//!   запросы прав и отправляет их в Telegram; ответ агента приходит одним
//!   сообщением и правкается на месте, поэтому лента не растёт как в логе.
//!
//! Чужой шум не проходит: бот работает по long polling, а `chat_id` в
//! конфиге — единственный источник сообщений. Апдейты от других чатов и от
//! групп отбрасываются, подпись команд не проверяется, потому что проверять
//! нечего: доступ и так ограничен одним чатом.
//!
//! Ответы на запросы прав приходят не сообщением, а нажатием кнопки:
//! `callback_data` несёт id запроса, поэтому «Разрешить» всегда относится к
//! тому же запросу, который человек видит на экране.
//!
//! Секрет бота лежит в `~/.config/hudbar/telegram.json` и не попадает ни в
//! журнал, ни в `Debug`: в `Debug` на его месте строка `<redacted>`, иначе
//! отладочный вывод унёс бы токен в лог.

